#!/usr/bin/env node
/* v8 WP1: build core/icons.js from the vendored Lucide SVGs (vendor/lucide-static-1.76.0, byte-identical to the npm
 * release). Each file's inner markup becomes one <symbol id="i-NAME" viewBox="0 0 24 24">; the root attributes
 * (stroke, width, caps) move to CSS (.i in css/v8.css). Deterministic: same files → same core/icons.js.
 *   node tools/make-sprite.cjs          (tests/icons.test.cjs fails if core/icons.js is stale) */
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), DIR = path.join(ROOT, 'vendor/lucide-static-1.76.0');
function symbols() {
  return fs.readdirSync(DIR).filter((f) => f.endsWith('.svg')).sort().map((f) => {
    const src = fs.readFileSync(path.join(DIR, f), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
    const inner = src.match(/<svg[^>]*>([\s\S]*)<\/svg>/)[1].replace(/\s+/g, ' ').replace(/> </g, '><').replace(/\s*\/>/g, '/>').replace(/"/g, "'").trim();
    return [f.replace(/\.svg$/, ''), inner];
  });
}
function build() {
  const S = symbols();
  const sprite = "<svg xmlns='http://www.w3.org/2000/svg' id='oracle-icons' aria-hidden='true' focusable='false' style='position:absolute;width:0;height:0;overflow:hidden'>" +
    S.map(([n, b]) => `<symbol id='i-${n}' viewBox='0 0 24 24'>${b}</symbol>`).join('') + '</svg>';
  return `/* GENERATED by tools/make-sprite.cjs from vendor/lucide-static-1.76.0 (Lucide, ISC — see THIRD_PARTY_NOTICES.md). Do not edit.
 * v8 WP1: one inline SVG sprite (no network: it is part of this script) and a helper. Icons are decorative:
 * every icon is aria-hidden; the visible caption beside it is the control's name. */
(function (root) {
  'use strict';
  const NAMES = ${JSON.stringify(S.map(([n]) => n))};
  const SPRITE = ${JSON.stringify(sprite)};
  /** svg('compass') → an aria-hidden 24 px icon that draws symbol #i-compass in currentColor. Unknown name → ''. */
  const svg = (name, cls) => NAMES.includes(name) ? \`<svg class="i\${cls ? ' ' + cls : ''}" aria-hidden="true" focusable="false" width="24" height="24"><use href="#i-\${name}"></use></svg>\` : '';
  function mount(doc) {
    doc = doc || (typeof document !== 'undefined' ? document : null);
    if (!doc || !doc.body || doc.getElementById('oracle-icons')) return false;
    doc.body.insertAdjacentHTML('afterbegin', SPRITE); return true;
  }
  const api = { NAMES, SPRITE, svg, mount };
  root.OracleIcons = api;
  if (typeof module !== 'undefined') module.exports = api;
  if (typeof document !== 'undefined') { if (document.body) mount(document); else document.addEventListener('DOMContentLoaded', () => mount(document)); }
})(typeof window !== 'undefined' ? window : globalThis);
`;
}
module.exports = { build, symbols, DIR };
if (require.main === module) { fs.writeFileSync(path.join(ROOT, 'core/icons.js'), build()); console.log('core/icons.js written:', symbols().length, 'icons'); }
